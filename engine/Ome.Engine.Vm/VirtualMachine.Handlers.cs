    /// <summary>The names the handler table binds.</summary>
    public static IReadOnlyCollection<string> HandlerNames => HandlersByName.Keys;

    /// <summary>Whether the VM runs <paramref name="opcode"/> under <paramref name="table"/>: the table has it and the
    /// handler table binds its name.</summary>
    public static bool Implements(OpcodeTable table, int opcode)
    {
        ArgumentNullException.ThrowIfNull(table);
        return table.TryGetDefinition(opcode, out OpcodeDefinition definition)
               && HandlersByName.ContainsKey(definition.CanonicalLabel);
    }

    /// <summary>Each opcode of <paramref name="table"/> bound to its handler, indexed by opcode; null for an opcode
    /// the table lacks or no handler implements.</summary>
    private static Handler?[] BindHandlers(OpcodeTable table)
    {
        int size = 0;
        foreach (OpcodeDefinition definition in table.Entries)
            size = Math.Max(size, definition.Opcode + 1);
        var handlers = new Handler?[size];
        foreach (OpcodeDefinition definition in table.Entries)
            if (definition.Opcode >= 0 && HandlersByName.TryGetValue(definition.CanonicalLabel, out Handler? handler))
                handlers[definition.Opcode] = handler;
        return handlers;
    }
