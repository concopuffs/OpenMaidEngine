using System.Globalization;
using System.Text;
using Ome.Engine.Modding;
using Ome.Engine.Natives;
using Ome.Mods.Linking;

namespace Ome.Mods.Tools;

/// <summary>
/// <c>omp lua-stubs</c> (Lua scripting spec §13): definitions for lua-language-server, as <c>---@meta</c> files an editor
/// reads from its <c>workspace.library</c>. <c>maid.lua</c> describes the engine's API (spec §8) and the contexts a
/// handler is given; <c>events.lua</c> each declared event's fields (spec §9.2); <c>&lt;base mod id&gt;.lua</c> what
/// <c>require</c> gives for each base mod (spec §9.3): <c>g</c> with every scalar's name and <c>table</c> with every
/// table's. Nothing here runs: the files only name types.
/// </summary>
public static class LuaStubs
{
    public const string MaidFile = "maid.lua", EventsFile = "events.lua";

    /// <summary>The engine events' fields (spec §7.7), as the scripting native raises them.</summary>
    public static readonly IReadOnlyDictionary<string, (string Field, string Type, string Doc)> EngineEventFields =
        new Dictionary<string, (string, string, string)>(StringComparer.Ordinal)
        {
            [Scripting.SessionStartEvent] = ("reason", "\"boot\"|\"title\"|\"load\"", "why the session was built"),
            [Scripting.SessionResumedEvent] = ("slot", "integer", "the slot the load read"),
            [Scripting.SaveWritingEvent] = ("slot", "integer", "the slot the save writes"),
        };

    /// <summary>The files, by name, for the base mods' layouts and the declared events. <paramref name="helpers"/> holds a
    /// base mod's <c>lua/init.lua</c> by its id, whose helpers its file then describes.</summary>
    public static IReadOnlyDictionary<string, string> Files(IReadOnlyList<BaseModLayout> bases, IReadOnlyList<GameEvent> events,
                                                            IReadOnlyDictionary<string, string>? helpers = null)
    {
        var files = new SortedDictionary<string, string>(StringComparer.Ordinal)
        {
            [MaidFile] = Maid(),
            [EventsFile] = Events(events),
        };
        foreach (BaseModLayout layout in bases)
            files[$"{layout.ModId}.lua"] = Base(layout, helpers?.GetValueOrDefault(layout.ModId));
        return files;
    }

    private static readonly System.Text.RegularExpressions.Regex Returned = new(@"^return\s+([A-Za-z_]\w*)\s*;?\s*$");
    private static readonly System.Text.RegularExpressions.Regex Function = new(@"^function\s+([A-Za-z_]\w*)\.([A-Za-z_]\w*)\s*\(([^)]*)\)");

    /// <summary>
    /// The helpers a base mod's <c>init.lua</c> returns (spec §9.3), each as its annotation block and an empty body: every
    /// top-level <c>function T.name(…)</c> whose <c>T</c> is the table the file's last top-level <c>return T</c> names,
    /// with the <c>---</c> lines just above it. Nothing runs: a helper the file builds another way is not described.
    /// </summary>
    public static IReadOnlyList<string> Helpers(string init)
    {
        string[] lines = init.Replace("\r\n", "\n").Split('\n');
        string? module = lines.Select(line => Returned.Match(line)).LastOrDefault(match => match.Success)?.Groups[1].Value;
        var found = new List<string>();
        if (module == null) return found;
        for (int i = 0; i < lines.Length; i++)
        {
            var match = Function.Match(lines[i]);
            if (!match.Success || match.Groups[1].Value != module) continue;
            int first = i;
            while (first > 0 && lines[first - 1].StartsWith("---", StringComparison.Ordinal)) first--;
            var text = new StringBuilder();
            for (int k = first; k < i; k++) text.Append(lines[k].TrimEnd()).Append('\n');
            text.Append($"function M.{match.Groups[2].Value}({match.Groups[3].Value.Trim()}) end\n");
            found.Add(text.ToString());
        }
        return found;
    }

    private const string Header = "-- Generated by omp lua-stubs (docs/modding/lua.md, \"Editor definitions\"). Do not edit: run it again.\n";

    /// <summary>A Lua name for a class: a mod id's dashes become underscores.</summary>
    public static string ClassName(string id) => id.Replace('-', '_');

    private static string Maid()
    {
        var text = new StringBuilder();
        text.Append("---@meta\n").Append(Header).Append('\n');
        text.Append("""
            ---The engine's API (Lua scripting spec §8).
            ---@class maid
            ---@field vm maid.vm? present with [lua] capabilities = ["vm"]
            ---@field names maid.names? present in a base mod and in the console
            ---@field log maid.log
            ---@field mod maid.mod
            ---@field session maid.session
            ---@field events maid.events
            ---@field state table the mod's own table, kept beside each numbered save
            maid = {}

            ---@class maid.log
            ---@field info fun(...: any) a line in diagnostics/lua.log
            ---@field warn fun(...: any)
            ---@field error fun(...: any)

            ---@class maid.mod
            ---@field id string
            ---@field version string
            ---@field state_version string? the version that wrote the loaded state

            ---@class maid.session
            ---@field reason "boot"|"title"|"load" why the session was built
            ---@field restoring boolean true while a load restores its frames

            ---@class maid.events
            ---@field emit fun(name: string, fields: table): table raise an event your mod declares with raised_by = "lua"

            ---@class maid.vm.integers
            ---@field [integer] integer
            local integers = {}
            ---Many cells in one call.
            ---@param address integer
            ---@param count integer
            ---@return integer[]
            function integers:range(address, count) end

            ---@class maid.vm.floats
            ---@field [integer] number
            local floats = {}
            ---@param address integer
            ---@param count integer
            ---@return number[]
            function floats:range(address, count) end

            ---@class maid.vm.strings
            ---@field [integer] string
            local strings = {}
            ---@param address integer
            ---@param count integer
            ---@return string[]
            function strings:range(address, count) end

            ---@class maid.vm.frame
            ---@field script string
            ---@field offset integer the instruction's offset in the linked script
            ---@field depth integer
            ---@field site integer? the offset in the base script; absent for code a patch inserted
            ---@field changed_by string[]? the mods that patched or replaced the script

            ---Raw access (capability vm, spec §8.1).
            ---@class maid.vm
            ---@field g maid.vm.integers integer globals
            ---@field gf maid.vm.floats float globals
            ---@field gs maid.vm.strings string globals
            ---@field gp maid.vm.integers pointer cells: read only
            ---@field gsp maid.vm.integers string pointer cells: read only
            ---@field l maid.vm.integers the frame's integer locals
            ---@field lf maid.vm.floats the frame's float locals
            ---@field ls maid.vm.strings the frame's string locals
            ---@field frame maid.vm.frame? the frame the hook fired in
            ---@field frames fun(): maid.vm.frame[] the call stack, outermost first
            ---@field script_id fun(name: string): integer? a catalog name's packed id

            ---A base mod's own accessors (spec §8.4): g and table over its layout, with no write list.
            ---@class maid.names
            ---@field g table<string, integer|number|string>
            ---@field table fun(name: string): table

            ---An operand of the hooked instruction (ctx.args[i]).
            ---@class maid.arg
            ---@field value integer|number|string a write changes the cell the operand names
            ---@field kind "integer"|"float"|"string"
            ---@field writable boolean false for an immediate or a literal

            ---What a point hook and a site hook are given (spec §7.1).
            ---@class maid.point
            ---@field point string|nil the point's name; nil at a site that is no point
            ---@field script string
            ---@field offset integer
            ---@field site integer
            ---@field opcode integer
            ---@field args maid.arg[]
            ---@field skipped boolean whether a handler before the instruction skipped it
            ---@field skip fun(self: maid.point) pass over the instruction; a hook before it with skip = true

            ---What a script hook is given (spec §7.2).
            ---@class maid.script
            ---@field script string
            ---@field cause "call"|"root"|"title"|"restore" why the frame was entered

            ---What a watch handler is given (spec §7.3): one write to a watched cell.
            ---@class maid.watch
            ---@field watch string the watch as the manifest names it
            ---@field address integer the cell's address
            ---@field name string|nil the global the cell belongs to; nil for a cell no base mod names
            ---@field index integer|nil the cell's row in a table
            ---@field column integer|nil the cell's column in a 2-D table
            ---@field old integer|string the value before the write
            ---@field new integer|string the value it wrote
            ---@field writer "script"|"mod"|"console"|"engine" what wrote it
            ---@field mod string|nil the writing mod, when a mod's Lua wrote
            ---@field script string|nil the writing instruction's script, when an instruction wrote
            ---@field offset integer|nil its offset in the linked script
            ---@field site integer|nil its original offset; nil for an instruction a patch inserted

            """);
        foreach (var (name, (field, type, doc)) in EngineEventFields.OrderBy(pair => pair.Key, StringComparer.Ordinal))
            text.Append($"---What an {name} handler is given (spec §7.7).\n---@class {name}\n---@field event \"{name}\"\n")
                .Append($"---@field {field} {type} {doc}\n\n");
        return text.ToString();
    }

    private static string Events(IReadOnlyList<GameEvent> events)
    {
        var text = new StringBuilder();
        text.Append("---@meta\n").Append(Header);
        if (events.Count == 0) text.Append("-- The stack declares no event.\n");
        foreach (GameEvent gameEvent in events.OrderBy(entry => entry.Name, StringComparer.Ordinal))
        {
            text.Append('\n');
            if (gameEvent.Description is { Length: > 0 } description)
                foreach (string line in description.Split('\n')) text.Append($"---{line.TrimEnd()}\n");
            string where = gameEvent.RaisedByLua ? "raised from Lua" : $"raised at {gameEvent.Point}";
            text.Append($"---Declared by {gameEvent.Owner}, {where}. Subscribe in the manifest: [[hooks]] event = \"{gameEvent.Name}\".\n");
            text.Append($"---@class {gameEvent.Name}\n---@field event \"{gameEvent.Name}\"\n");
            foreach (GameEventField field in gameEvent.Fields)
            {
                string type = field.Type switch
                {
                    EventFieldType.Int => "integer",
                    EventFieldType.Float => "number",
                    EventFieldType.Bool => "boolean",
                    _ => "string",
                };
                text.Append($"---@field {field.Name} {type} {(field.Writable ? "rw" : "read-only")}"
                            + (field.At is { } at ? $": {at}" : "") + "\n");
            }
        }
        return text.ToString();
    }

    private static string Base(BaseModLayout layout, string? init)
    {
        string module = ClassName(layout.ModId);
        var text = new StringBuilder();
        text.Append($"---@meta {layout.ModId}\n").Append(Header).Append('\n');

        static string Value(CellKind kind) => kind switch
        {
            CellKind.Float => "number",
            CellKind.String => "string",
            _ => "integer",
        };
        static string Cell(LayoutGlobal global) => string.Create(CultureInfo.InvariantCulture,
            $"{global.Kind switch { CellKind.Float => "GF", CellKind.String => "GS", _ => "G" }}[0x{global.Address:x}]");
        static IEnumerable<string> Names(LayoutGlobal global) => global.Aliases.Prepend(global.Name);

        // g: every scalar, by its name and its aliases.
        text.Append($"---The scalar globals {layout.ModId} names (read any; write the ones [lua] writes lists).\n");
        text.Append($"---@class {module}.g\n");
        foreach (LayoutGlobal global in layout.Layout.Globals.Where(global => global.IsScalar))
            foreach (string name in Names(global))
                text.Append($"---@field {name} {Value(global.Kind)} {Cell(global)}"
                            + (name == global.Name ? "" : $", the old name of {global.Name}") + "\n");
        text.Append('\n');

        // A class per table: its elements, or its rows and their named columns.
        var tables = layout.Layout.Globals.Where(global => !global.IsScalar).ToList();
        foreach (LayoutGlobal global in tables)
        {
            string rows = global.Rows is int count ? $"{count} rows" : "rows to the end of the bank";
            if (global.Dimensions.Count == 2)
            {
                text.Append($"---A row of {global.Name}: {global.RowWidth} cells.\n---@class {module}.{global.Name}.row\n");
                text.Append($"---@field [integer] {Value(global.Kind)}\n");
                foreach (var (column, index) in global.Columns.OrderBy(pair => pair.Value))
                    text.Append($"---@field {column} {Value(global.Kind)} column {index}\n");
                text.Append($"\n---{global.Name}, from {Cell(global)}: {rows}, each a row.\n---@class {module}.{global.Name}\n");
                text.Append($"---@field [integer] {module}.{global.Name}.row\n\n");
            }
            else
            {
                text.Append($"---{global.Name}, from {Cell(global)}: {rows}.\n---@class {module}.{global.Name}\n");
                text.Append($"---@field [integer] {Value(global.Kind)}\n");
                foreach (var (column, index) in global.Columns.OrderBy(pair => pair.Value))
                    text.Append($"---@field {column} {Value(global.Kind)} element {index}\n");
                text.Append('\n');
            }
        }

        text.Append($"---What require(\"{layout.ModId}\") gives (spec §9.3), beside what its lua/init.lua returns.\n");
        text.Append($"---@class {module}\n---@field g {module}.g\nlocal M = {{}}\n\n");
        text.Append("---A table global by name; its indices are the game's, from 0.\n");
        foreach (LayoutGlobal global in tables)
            foreach (string name in Names(global))
                text.Append($"---@overload fun(name: \"{name}\"): {module}.{global.Name}\n");
        text.Append("---@param name string\n---@return table\nfunction M.table(name) end\n\n");
        IReadOnlyList<string> helpers = init == null ? [] : Helpers(init);
        if (helpers.Count > 0)
        {
            text.Append($"-- The helpers {layout.ModId}'s lua/init.lua returns.\n\n");
            foreach (string helper in helpers) text.Append(helper).Append('\n');
        }
        text.Append("return M\n");
        return text.ToString();
    }

    /// <summary>The stubs for the stack <paramref name="result"/> linked, with the profile's shipped base mod added when
    /// the stack does not mount it, so a mod not yet written has the game's names. <c>Helpers</c> holds each base mod's
    /// <c>lua/init.lua</c>.</summary>
    public static (IReadOnlyList<BaseModLayout> Bases, IReadOnlyList<GameEvent> Events, IReadOnlyDictionary<string, string> Helpers)
        Inputs(ModLinkBase linkBase, ModLinkResult result)
    {
        var bases = result.Lua.Stack.Mods.Where(mod => mod.Layout != null)
            .Select(mod => new BaseModLayout(mod.Id, mod.Layout!)).ToList();
        var helpers = new Dictionary<string, string>(StringComparer.Ordinal);
        void Keep(IEnumerable<ModRuntimeMod> mods)
        {
            foreach (ModRuntimeMod mod in mods.Where(mod => mod.Layout != null))
                if (mod.Files.FirstOrDefault(file => file.Path == "init.lua") is { } init) helpers[mod.Id] = init.Text;
        }
        Keep(result.Lua.Stack.Mods);
        var events = result.Lua.Stack.EventList.ToList();
        string profileBase = $"{linkBase.Profile}-base";
        if (bases.All(layout => layout.ModId != profileBase)
            && Ome.Mods.Packages.ShippedPackages.Open(profileBase) is { } shipped)
        {
            using (shipped)
            {
                ModLinkResult alone = ModLinker.Link(linkBase, [shipped], []);
                if (alone.Succeeded)
                {
                    bases.AddRange(alone.Lua.Stack.Mods.Where(mod => mod.Layout != null)
                                       .Select(mod => new BaseModLayout(mod.Id, mod.Layout!)));
                    Keep(alone.Lua.Stack.Mods);
                    events.AddRange(alone.Lua.Stack.EventList.Where(added => events.All(held => held.Name != added.Name)));
                }
            }
        }
        return (bases, events, helpers);
    }
